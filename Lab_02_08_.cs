{
    static void Main()
    {
        int n, a = 0, b = 1, c = 0;

        Console.Write("Enter n: ");
        n = Convert.ToInt32(Console.ReadLine());

        for (int i = 2; i <= n; i++)
        {
            c = a + b;
            a = b;
            b = c;
        }

        Console.WriteLine("Nth term = " + (n == 0 ? a : b));
    }
